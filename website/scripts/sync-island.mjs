#!/usr/bin/env node
/**
 * Sync the real FluidBar prototype into the website's clean embed shell.
 *
 * Source (read-only): docs/rewrite/prototype2
 * Target:             website/public/island
 *
 * The prototype is the single source of truth for the island, wallpaper,
 * taskbar and dock. This script never edits it; it copies the runtime files
 * verbatim and generates embed.html from the prototype's index.html by:
 *
 *   1. linking embed.css after the prototype stylesheet,
 *   2. loading embed-bridge.js after app.js,
 *   3. setting data-theme="light" on <body> (the prototype's own app.js then
 *      applies its real dark desktop theme on boot; see the embed doc).
 *
 * The hand-written embed.css and embed-bridge.js live next to the generated
 * files in website/public/island and are left untouched.
 *
 * Usage:
 *   node website/scripts/sync-island.mjs
 *   node website/scripts/sync-island.mjs --check   # exit 1 if output is stale
 */

import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..', '..');
const PROTOTYPE_DIR = path.join(REPO_ROOT, 'docs', 'rewrite', 'prototype2');
const OUT_DIR = path.join(REPO_ROOT, 'website', 'public', 'island');

/** Runtime files copied verbatim from the prototype. */
const COPIED_FILES = ['app.js', 'icons.js', 'styles.css'];

const GENERATED_HEADER =
  '<!-- Generated by website/scripts/sync-island.mjs from docs/rewrite/prototype2/index.html.\n' +
  '     Do not edit by hand; edit the prototype or the sync script instead. -->';

const checkOnly = process.argv.includes('--check');

/** Fail loudly instead of writing an embed that silently lost a patch. */
function mustReplace(source, pattern, replacement, label) {
  if (!pattern.test(source)) {
    throw new Error(
      `sync-island: could not find ${label} in docs/rewrite/prototype2/index.html. ` +
        'The prototype markup changed; update website/scripts/sync-island.mjs.',
    );
  }
  return source.replace(pattern, replacement);
}

/** Turn the prototype's index.html into the website embed shell. */
function buildEmbedHtml(prototypeIndex) {
  let html = prototypeIndex;

  // 1. Mark the generated artifact.
  html = mustReplace(html, /<head>/, `<head>\n  ${GENERATED_HEADER}`, '<head>');

  // 2. Load the embed stylesheet directly after the prototype stylesheet.
  html = mustReplace(
    html,
    /(\s*)<link rel="stylesheet" href="styles\.css">/,
    '$1<link rel="stylesheet" href="styles.css">$1<link rel="stylesheet" href="embed.css">',
    'the styles.css <link>',
  );

  // 3. Static shell theme is the website's light theme; app.js applies the
  //    prototype's real theme (dark by default) during boot.
  html = mustReplace(
    html,
    /(<body\b[^>]*\bdata-theme=")dark(")/,
    '$1light$2',
    'the <body data-theme> attribute',
  );

  // 4. Load the postMessage bridge after app.js so the prototype is booted first.
  html = mustReplace(
    html,
    /(\s*)<script src="app\.js"><\/script>/,
    '$1<script src="app.js"></script>$1<script src="embed-bridge.js"></script>',
    'the app.js <script>',
  );

  return html;
}

async function main() {
  const embedHtmlPath = path.join(OUT_DIR, 'embed.html');
  const prototypeIndex = await readFile(path.join(PROTOTYPE_DIR, 'index.html'), 'utf8');
  const embedHtml = buildEmbedHtml(prototypeIndex);

  await mkdir(OUT_DIR, { recursive: true });

  if (checkOnly) {
    const current = await readFile(embedHtmlPath, 'utf8').catch(() => null);
    if (current !== embedHtml) {
      console.error('sync-island: website/public/island/embed.html is stale (run without --check).');
      process.exit(1);
    }
    console.log('sync-island: embed.html is up to date.');
    return;
  }

  for (const file of COPIED_FILES) {
    const from = path.join(PROTOTYPE_DIR, file);
    const to = path.join(OUT_DIR, file);
    await copyFile(from, to);
    console.log(`sync-island: copied ${file}`);
  }

  await writeFile(embedHtmlPath, embedHtml, 'utf8');
  console.log('sync-island: wrote embed.html');
  console.log(`sync-island: source   ${path.relative(REPO_ROOT, PROTOTYPE_DIR)}`);
  console.log(`sync-island: target   ${path.relative(REPO_ROOT, OUT_DIR)}`);
  console.log('sync-island: done. embed.css and embed-bridge.js are hand-written and were not touched.');
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
